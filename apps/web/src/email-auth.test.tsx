it('removes a reset secret from the URL and only sends it when saving a new password', async () => {
  const token = 'a'.repeat(64)
  window.history.replaceState(null, '', `/#reset_token=${token}`)
  const fetch = vi.fn(async (_path: string, _init?: RequestInit) => new Response('{"ok":true}'))
  vi.stubGlobal('fetch', fetch)
  render(<Application />)
  await screen.findByText('Crie uma nova senha')
  expect(window.location.hash).toBe('')
  expect(fetch).not.toHaveBeenCalled()
  const user = userEvent.setup()
  await user.type(screen.getByLabelText('Nova senha'), 'new-password-123')
  await user.type(screen.getByLabelText('Confirmar nova senha'), 'different-password')
  await user.click(screen.getByRole('button', { name: 'Salvar nova senha' }))
  expect((await screen.findByRole('alert')).textContent).toBe('As senhas não coincidem.')
  expect(fetch).not.toHaveBeenCalled()
  await user.clear(screen.getByLabelText('Confirmar nova senha'))
  await user.type(screen.getByLabelText('Confirmar nova senha'), 'new-password-123')
  await user.click(screen.getByRole('button', { name: 'Salvar nova senha' }))
  await screen.findByText('Senha redefinida')
  expect(fetch.mock.calls).toHaveLength(1)
  expect(fetch.mock.calls[0][0]).toBe('/api/auth/password/reset')
  expect(JSON.parse((fetch.mock.calls[0] as any)[1].body)).toEqual({ token, password: 'new-password-123' })
  expect(localStorage.getItem('reset_token')).toBeNull()
})
it('keeps a user out of the dashboard after signup until confirmation and login', async () => {
  const fetch = vi.fn(async (path: string) => {
    if (path === '/api/auth/me') return new Response('{"error":"Não autenticado"}', { status: 401 })
    if (path === '/api/auth/register') return new Response('{"verificationRequired":true,"email":"new@example.test"}', { status: 201 })
    if (path === '/api/auth/email/verify') return new Response('{"ok":true}')
    throw new Error(`Unexpected path: ${path}`)
  })
  vi.stubGlobal('fetch', fetch)
  render(<Application />)
  const user = userEvent.setup()
  await screen.findByText('Bem-vindo de volta')
  await user.click(screen.getByRole('button', { name: 'Criar conta' }))
  await user.type(screen.getByLabelText('Nome'), 'Pessoa de teste')
  await user.type(screen.getByLabelText('E-mail'), 'new@example.test')
  await user.type(screen.getByPlaceholderText('Mínimo 10 caracteres'), 'password-12345')
  await user.type(screen.getByPlaceholderText('Repita a senha'), 'password-12345')
  await user.click(screen.getByRole('button', { name: 'Criar conta' }))
  await screen.findByText('Confirme seu e-mail')
  await user.type(screen.getByLabelText('Código de confirmação'), '123456')
  await user.click(screen.getByRole('button', { name: 'Confirmar e-mail' }))
  await screen.findByText('E-mail confirmado. Entre com sua senha para continuar.')
  expect(screen.getByText('Bem-vindo de volta')).toBeTruthy()
  expect(fetch.mock.calls.some(([path]) => path === '/api/companies')).toBe(false)
})
