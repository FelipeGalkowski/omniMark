import { expect, it, vi } from 'vitest'
import { render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import Application from './Application'
import LoginPage from './LoginPage'
import RecoveryInfo from './RecoveryInfo'
import VerifyEmailPage from './VerifyEmailPage'

it('does not sign in when the server requires mailbox confirmation', async () => {
  const onLogin = vi.fn(); const onVerify = vi.fn()
  vi.stubGlobal('fetch', vi.fn(async () => new Response(JSON.stringify({ verificationRequired: true, email: 'owner@example.test' }))))
  render(<LoginPage onLogin={onLogin} onVerify={onVerify} onSignup={() => {}} onForgot={() => {}} />)
  const user = userEvent.setup()
  await user.type(screen.getByLabelText('E-mail'), 'owner@example.test')
  await user.type(screen.getByLabelText('Senha'), 'password-12345')
  await user.click(screen.getByRole('button', { name: 'Entrar' }))
  await waitFor(() => expect(onVerify).toHaveBeenCalledWith('owner@example.test'))
  expect(onLogin).not.toHaveBeenCalled()
})
it('confirms a six digit code once and keeps failed codes on the confirmation screen', async () => {
  const onVerified = vi.fn()
  const fetch = vi.fn().mockResolvedValueOnce(new Response(JSON.stringify({ error: 'Código expirado.' }), { status: 400 })).mockResolvedValue(new Response('{"ok":true}'))
  vi.stubGlobal('fetch', fetch)
  render(<VerifyEmailPage email="owner@example.test" onVerified={onVerified} onBack={() => {}} />)
  const user = userEvent.setup()
  await user.type(screen.getByLabelText('Código de confirmação'), '123456')
  expect((screen.getByRole('button', { name: /Reenviar em/ }) as HTMLButtonElement).disabled).toBe(true)
  await user.click(screen.getByRole('button', { name: 'Confirmar e-mail' }))
  expect((await screen.findByRole('alert')).textContent).toBe('Código expirado.')
  expect(onVerified).not.toHaveBeenCalled()
  await user.click(screen.getByRole('button', { name: 'Confirmar e-mail' }))
  await waitFor(() => expect(onVerified).toHaveBeenCalledTimes(1))
  expect(JSON.parse(fetch.mock.calls[0][1].body)).toEqual({ email: 'owner@example.test', code: '123456' })
})
